"""Writes the app key into the generated, git-ignored module smtv_core/_appkey.py, for a build of the apps.

    SMTV_APP_KEY=... python scripts/write_appkey.py

In GitHub Actions the key comes from the secret SMTV_APP_KEY. Without it the build stops (an app without a key would
have links switched off); `--optional` writes nothing and succeeds with a warning instead (a local build).

    python scripts/write_appkey.py --verify dist

checks every smtv-core wheel and sdist in `dist`: one without the key fails the build (release workflows run this).
"""
from __future__ import annotations

import os
import re
import sys
import tarfile
import zipfile
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "packages" / "smtv-core" / "src" / "smtv_core" / "_appkey.py"


MEMBER = "smtv_core/_appkey.py"


def _has_key(text: str) -> bool:
    return bool(re.search(r'^KEY = "[^"\s]+"', text, re.M))


def verify(folder: Path) -> int:
    """Every smtv-core wheel and sdist in `folder` carries a non-empty key."""
    found, bad = 0, []
    for path in sorted(folder.glob("smtv_core-*.whl")) + sorted(folder.glob("smtv_core-*.tar.gz")):
        found += 1
        try:
            if path.suffix == ".whl":
                with zipfile.ZipFile(path) as z:
                    text = z.read(MEMBER).decode("utf-8") if MEMBER in z.namelist() else ""
            else:
                with tarfile.open(path) as t:
                    member = next((m for m in t.getmembers() if m.name.endswith("/src/" + MEMBER)), None)
                    f = t.extractfile(member) if member else None
                    text = f.read().decode("utf-8") if f else ""
        except (OSError, KeyError, zipfile.BadZipFile, tarfile.TarError):
            text = ""
        if not _has_key(text):
            bad.append(path.name)
    if not found:
        print(f"no smtv-core wheel or sdist in {folder}", file=sys.stderr)
        return 1
    if bad:
        print("built without the app key (links would be off for everybody who gets it): " + ", ".join(bad), file=sys.stderr)
        return 1
    print(f"the app key is in {found} smtv-core file(s)")
    return 0


def main(argv: list[str]) -> int:
    if argv[:1] == ["--verify"]:
        return verify(Path(argv[1]) if len(argv) > 1 else Path("dist"))
    key = os.environ.get("SMTV_APP_KEY", "").strip()
    if not key:
        if "--optional" in argv:
            print("WARNING: SMTV_APP_KEY is not set: no key written, links will be off in this build (fine locally, never for a release)", file=sys.stderr)
            return 0
        print("SMTV_APP_KEY is not set: refusing to build an app without it (--optional builds without)", file=sys.stderr)
        return 1
    if not key.isprintable() or any(c in key for c in " \"'\\\n"):
        print("SMTV_APP_KEY has characters that do not belong in a key", file=sys.stderr)
        return 1
    TARGET.write_text(f'"""Generated by scripts/write_appkey.py; git-ignored. Do not commit."""\nKEY = "{key}"\n', encoding="utf-8")
    print(f"wrote {TARGET.name} ({len(key)} characters)")      # never the key itself
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
